def _pick(corpus):
    st = corpus.stages
    n = len(st)
    target = st[6 % n]
    decoy_provisional = st[13 % n]
    decoy_late = st[2 % n]
    red_herring = st[9 % n]
    return target, decoy_provisional, decoy_late, red_herring


def _verified_on_dates(corpus, target, decoy_provisional, decoy_late):
    """Every stage's own MODULE date -- the effective, real rollout date."""
    rows = {}
    for i, s in enumerate(corpus.stages):
        if s is target or s is decoy_late:
            date = "2034-%02d-%02d" % (4 + (i % 6), 1 + (i * 3) % 27)
        elif s is decoy_provisional:
            date = "2033-%02d-%02d" % (6 + (i % 5), 1 + (i * 7) % 27)
        else:
            date = "2033-%02d-%02d" % (1 + (i % 4), 2 + (i * 5) % 26)
        rows[s["name"]] = date
    return rows


def _declared_dates(corpus, effective, target, decoy_provisional):
    """Every stage's own DOCUMENT date -- what the document itself last confirmed.

    Matches the module's effective date for every stage except `target` and
    `decoy_provisional`, whose documents were never updated after their modules moved on: that
    mismatch is what "provisional" means. A solver cannot tell which two stages mismatch
    without comparing both dates for every one of them -- the values are ordinary dates, not a
    keyword a grep could single out.
    """
    declared = {}
    for i, s in enumerate(corpus.stages):
        if s is target or s is decoy_provisional:
            # a distinct, unremarkable-looking early date per stage, never the SAME literal
            # value twice, so no two mismatched stages share a grep-able substring
            declared[s["name"]] = "2032-%02d-%02d" % (1 + (i % 12), 1 + (i * 5) % 27)
        else:
            declared[s["name"]] = effective[s["name"]]
    return declared


def _add_declared_row(seed, stage, date):
    path = os.path.join(seed, *stage["doc"].split("/"))
    text = C.read(path)
    new = re.sub(
        r"(^\| `window_s` \|.*\n)",
        r"\1| `declared_verified_on` | %s | the date this document itself was last confirmed "
        r"current; see the stage's own module for the effective date |\n" % date,
        text, count=1, flags=re.M)
    assert new != text, "declared date row not inserted for %s" % stage["name"]
    C.write(path, new)


def _set_verified_on(seed, stage, date):
    """Write `ROLLOUT_VERIFIED_ON` on its own line: the value and nothing else on that line,

    so `r2/check_index_leak.py` can read it back and confirm no other file echoes it beside
    the stage's own name.
    """
    path = os.path.join(seed, *stage["src"].split("/"))
    text = C.read(path)
    marker = "DEFAULT_%s_WINDOW_S = %d\n" % (stage["name"].upper(), stage["window"])
    assert marker in text, "window constant not found for %s" % stage["name"]
    new = text.replace(marker, marker + 'ROLLOUT_VERIFIED_ON = "%s"\n' % date, 1)
    assert new != text, "rollout date not inserted for %s" % stage["name"]
    C.write(path, new)


