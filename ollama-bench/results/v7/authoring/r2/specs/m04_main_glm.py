def _load_run_checks(ctx):
    """Import the seed's own checker to derive the ground truth from it.

    `sys.dont_write_bytecode` is set for the duration, and any `__pycache__` the import leaves
    is swept. Without it the import drops a `tools/__pycache__` into `seed/`, which
    `validate_all.py` reports as a build artifact in the material and is right to: a candidate
    whose material contains the residue of its own authoring is not the tree the model is
    supposed to be given. Found by `validate_all.py` on the round's final run (D7-8's family).
    """
    import importlib.util
    import shutil
    import sys as _sys

    path = os.path.join(ctx["seed"], *RUN_CHECKS.split("/"))
    prev = _sys.dont_write_bytecode
    _sys.dont_write_bytecode = True
    try:
        spec = importlib.util.spec_from_file_location("m04_run_checks", path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    finally:
        _sys.dont_write_bytecode = prev
        cache = os.path.join(os.path.dirname(path), "__pycache__")
        if os.path.isdir(cache):
            shutil.rmtree(cache, ignore_errors=True)
    return mod


def _compute(ctx):
    mod = _load_run_checks(ctx)
    return mod.compute(ctx["seed"])


