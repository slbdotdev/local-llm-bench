def _material_rows(ctx):
    """Read both date sources for every stage and derive the complete fixture rows."""
    corpus = ctx["corpus"]
    rows = []
    for s in corpus.stages:
        doc = C.read(corpus.path(s["doc"]))
        module = C.read(corpus.path(s["src"]))
        dm = re.search(r"^\| `declared_verified_on` \| ([0-9-]+) \|", doc, re.M)
        mm = re.search(r'^ROLLOUT_VERIFIED_ON = "([0-9-]+)"$', module, re.M)
        assert dm and mm, "both date fields required for %s" % s["name"]
        declared, effective = dm.group(1), mm.group(1)
        provisional = declared != effective
        included = not (provisional and effective >= CUTOVER)
        rows.append({"stage": s["name"], "declared_date": declared,
                     "effective_date": effective, "included": "yes" if included else "no"})
    return rows


def _fixture_digest(rows):
    body = "\n".join("|".join(row[k] for k in _FIXTURE_FIELDS) for row in rows) + "\n"
    return hashlib.sha256(body.encode("utf-8")).hexdigest()

