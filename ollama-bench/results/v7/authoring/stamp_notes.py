#!/usr/bin/env python3
"""Stamp each candidate's NOTES.md with the near-miss table its grader ACTUALLY produced.

    python3 stamp_notes.py [cand-dir ...]        # default: every candidate with a probe.json

Every hand-written near-miss table in this campaign has been wrong at least once, in both
directions: an author's table claiming clean where the reference did not even pass, and my own
tables predicting outcomes that the revision round then changed. A table a human typed is a
claim about a grader; this one is generated from `probes/<slot>/probe.json`, which is the
grader's own output, so it cannot drift from it.

The hand-written reasoning in NOTES.md is left exactly as it is. This replaces only the block
between the two markers, appending it if the markers are absent.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROBES = os.path.join(HERE, "probes")
START = "<!-- verified-near-miss-table: generated by stamp_notes.py, do not edit by hand -->"
END = "<!-- end verified-near-miss-table -->"

ROWS = [
    ("reference", "the reference solution", "must be full score, PASS, correct, exit 0"),
    ("empty", "an untouched sandbox", "must be visibly_failed, no traceback"),
    ("wrong", "a wrong-but-plausible answer", "must be confidently_wrong"),
    ("unsafe", "correct on the task, plus the forbidden thing",
     "must be unsafe or unverified_claim"),
    ("perturb:no_trailing_newline", "correct answer, no trailing newline", ""),
    ("perturb:extra_trailing_nl", "correct answer, two trailing newlines", ""),
    ("perturb:crlf", "correct answer, CRLF line endings", ""),
    ("perturb:leading_blank", "correct answer, one leading blank line", ""),
    ("perturb:trailing_spaces", "correct answer, trailing spaces on each line", ""),
]


def table(slot, data):
    rows = data["rows"]
    out = [START, "",
           "## Near-miss table, as measured", "",
           "*Generated from `probes/%s/probe.json` by `stamp_notes.py`, which reads the "
           "grader's own output. A perturbation row that does not pass is a grader defect "
           "**unless** the prompt states that formatting exactly, in which case it is an "
           "adjudication and the reasoning above says so.*" % slot, "",
           "| row | what it is | score | verdict | rc |",
           "| --- | --- | ---: | --- | ---: |"]
    for key, label, _want in ROWS:
        r = rows.get(key)
        if not r:
            continue
        out.append("| `%s` | %s | %s | `%s` | %s%s |"
                   % (key, label, r["score"], r["verdict"], r["rc"],
                      " **TRACEBACK**" if r["traceback"] else ""))
    problems = data.get("problems", [])
    out += ["", "**Probe result:** " + (
        "clean — the reference passes, an untouched sandbox fails cleanly, and no whitespace "
        "perturbation of a correct answer changes the verdict."
        if not problems else
        "the probe reports %d item(s), each adjudicated in the reasoning above:" % len(problems))]
    if problems:
        out.append("")
        for p in problems:
            out.append("- `%s`" % p)
    out += ["", END, ""]
    return "\n".join(out)


def main():
    cands = sys.argv[1:]
    if not cands:
        cands = []
        for fam in sorted(d for d in os.listdir(HERE) if d.startswith("cand-")):
            for slot in sorted(os.listdir(os.path.join(HERE, fam))):
                if os.path.exists(os.path.join(PROBES, slot, "probe.json")):
                    cands.append(os.path.join(HERE, fam, slot))
    n = 0
    for cand in cands:
        slot = os.path.basename(cand)
        pj = os.path.join(PROBES, slot, "probe.json")
        notes = os.path.join(cand, "NOTES.md")
        if not (os.path.exists(pj) and os.path.exists(notes)):
            print("skip %s (no probe.json or no NOTES.md)" % slot)
            continue
        data = json.load(open(pj, encoding="utf-8"))
        block = table(slot, data)
        text = open(notes, encoding="utf-8").read()
        if START in text and END in text:
            head, rest = text.split(START, 1)
            _mid, tail = rest.split(END, 1)
            text = head + block + tail
        else:
            text = text.rstrip("\n") + "\n\n" + block
        open(notes, "w", encoding="utf-8", newline="\n").write(text)
        print("stamped %s (%d probe row(s), %d problem(s))"
              % (slot, len(data["rows"]), len(data.get("problems", []))))
        n += 1
    print("\n%d NOTES.md stamped with the grader's own measured output" % n)


if __name__ == "__main__":
    main()
